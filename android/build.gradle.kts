allprojects {
    repositories {
        google()
        mavenCentral()
    }
}

val newBuildDir: Directory =
    rootProject.layout.buildDirectory
        .dir("../../build")
        .get()
rootProject.layout.buildDirectory.value(newBuildDir)

subprojects {
    val newSubprojectBuildDir: Directory = newBuildDir.dir(project.name)
    project.layout.buildDirectory.value(newSubprojectBuildDir)
}
// Some plugin modules (e.g. flutter_pcm_sound) compile against an old SDK while
// their AndroidX deps need a newer one, failing checkAarMetadata. Force all
// Android library plugin modules up to at least SDK 36. (Not 37: android-37's
// stricter nullability annotations break flutter_ble_peripheral 3.1.0.)
subprojects {
    plugins.withId("com.android.library") {
        extensions.configure<com.android.build.api.variant.LibraryAndroidComponentsExtension> {
            finalizeDsl { if ((it.compileSdk ?: 0) < 36) it.compileSdk = 36 }
        }
    }
}
subprojects {
    project.evaluationDependsOn(":app")
}

tasks.register<Delete>("clean") {
    delete(rootProject.layout.buildDirectory)
}
